export function fmtDateL(lang: Lang, d?: string | null) {
  const t = makeT(lang);
  if (!d) return t("date.none");
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(d);
  if (!m) return d;
  const day = parseInt(m[3], 10);
  const mi = parseInt(m[2], 10) - 1;
  if (lang === "en") {
    const months = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
    return `${months[mi] ?? ""} ${day}`;
  }
  const months = ["січня", "лютого", "березня", "квітня", "травня", "червня", "липня", "серпня", "вересня", "жовтня", "листопада", "грудня"];
  return `${day} ${months[mi] ?? ""}`;
}

export function agoL(lang: Lang, ts?: number | null) {
  if (!ts) return "";
  const t = makeT(lang);
  const m = Math.round((Date.now() - ts) / 60000);
  if (m < 1) return t("ago.now");
  if (m < 60) return t("ago.min", { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return t("ago.hour", { n: h });
  return t("ago.day", { n: Math.round(h / 24) });
}

export function inviteTextL(lang: Lang, g: any) {
  const t = makeT(lang);
  return t("invite.text", {
    name: g.name,
    budget: g.budget || t("invite.anyBudget"),
    date: fmtDateL(lang, g.date),
    code: g.code,
    note: g.note ? "\n" + g.note + "\n" : "",
    owner: g.owner_name || "",
  });
}

